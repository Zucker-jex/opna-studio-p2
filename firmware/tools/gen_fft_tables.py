#!/usr/bin/env python3
"""Generate fft_tables.h: 256-point Hann window, Q15 twiddles, bit reversal and
the log-spaced display-bin map for OPNA Studio's spectrum analyser."""
import math

N = 256
FS = 7987200 / 144.0


def hann(i):
    return 0.5 - 0.5 * math.cos(2 * math.pi * i / (N - 1))


win = [max(0, min(32767, round(hann(i) * 32767))) for i in range(N)]
cos_t = [round(math.cos(2 * math.pi * k / N) * 32767) for k in range(N // 2)]
sin_t = [round(-math.sin(2 * math.pi * k / N) * 32767) for k in range(N // 2)]
rev = []
for i in range(N):
    v = 0
    for b in range(8):
        if i & (1 << b):
            v |= 1 << (7 - b)
    rev.append(v)

# 64 display bins, expanded towards the bass with a square curve.  At 55.5 kHz
# the FFT bin is 216.7 Hz, so a pure log map wastes the first 8 bars on bin 0.
# A mild spectral tilt is applied later in fft.c to keep the highs visible.
def bin_at(d):
    return int(round(127.0 * (d / 63.0) ** 2))

lo, hi = [], []
for d in range(64):
    a = max(0, min(127, bin_at(d)))
    b = max(a, min(127, bin_at(d + 1) - 1))
    lo.append(a)
    hi.append(b)


def arr(name, ctype, vals, per=16, fmt=str):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("  " + ",".join(fmt(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


lines = ["#ifndef FFT_TABLES_H", "#define FFT_TABLES_H", "#include <stdint.h>",
         "/* Auto-generated by firmware/tools/gen_fft_tables.py */", ""]
lines += arr("fft_win", "uint16_t", win, 12)
lines += arr("fft_cos", "int16_t", cos_t, 12)
lines += arr("fft_sin", "int16_t", sin_t, 12)
lines += arr("fft_rev", "uint8_t", rev, 16)
lines += arr("fft_lo", "uint8_t", lo, 16)
lines += arr("fft_hi", "uint8_t", hi, 16)
lines.append("#endif")
open("firmware/studio/fft_tables.h", "w").write("\n".join(lines) + "\n")
print("wrote firmware/studio/fft_tables.h")
print("display bins:", list(zip(lo[:8], hi[:8])), "...", list(zip(lo[-4:], hi[-4:])))
