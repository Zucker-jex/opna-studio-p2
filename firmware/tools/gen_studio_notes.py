#!/usr/bin/env python3
"""Generate the OPNA Studio frequency tables.

The OPNA FM phase accumulator is 20 bits and runs at PFM_MIX_RATE (55466.67 Hz).
With the channel's MUL register set to 1 the phase increment equals
(fnum << blk) >> 1, so

    f_out = (fnum * 2**blk / 2) * fs / 2**20
    fnum  = f_out * 2**21 / (fs * 2**blk)

We pick the block that puts fnum in the normal 1024..2047 range.  The SSG tone
divider is TP = round(249600 / (2*f)) and the hardware range is 1..4095.
"""
import math
import os

FS = 7987200 / 144.0        # 55466.666..
SSG_RATE = 7987200 / 32.0   # 249600


def midi_hz(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def fm_pair(n):
    best = None
    for blk in range(8):
        fnum = round(midi_hz(n) * 2 ** 21 / (FS * 2 ** blk))
        if 1 <= fnum <= 2047:
            # prefer the highest fnum <= 2047 (most resolution, standard octave)
            score = fnum if 1024 <= fnum <= 2047 else fnum // 2
            if best is None or score > best[0]:
                best = (score, blk, fnum)
    if best is None:
        blk = 7
        fnum = min(2047, max(1, round(midi_hz(n) * 2 ** 21 / (FS * 2 ** blk))))
        best = (0, blk, fnum)
    return best[1], best[2]


def ssg_div(n):
    return max(1, min(4095, round(SSG_RATE / (2.0 * midi_hz(n)))))


def main():
    os.makedirs("firmware/studio", exist_ok=True)
    lines = []
    lines.append("#ifndef STUDIO_NOTES_H")
    lines.append("#define STUDIO_NOTES_H")
    lines.append("/* Auto-generated by firmware/tools/gen_studio_notes.py.")
    lines.append("   128 MIDI notes -> (OPNA block, 11-bit fnum, SSG 12-bit divider). */")
    lines.append("#include <stdint.h>")
    lines.append("")
    blk, fnum, ssg = [], [], []
    for n in range(128):
        b, f = fm_pair(n)
        blk.append(b)
        fnum.append(f)
        ssg.append(ssg_div(n))

    def emit(name, vals, per):
        width = "uint8_t" if max(vals) < 256 else "uint16_t"
        lines.append(f"static const {width} {name}[128] = {{")
        for i in range(0, 128, per):
            lines.append("  " + ",".join(str(v) for v in vals[i:i + per]) + ",")
        lines.append("};")

    emit("studio_note_blk", blk, 16)
    emit("studio_note_fnum", fnum, 12)
    emit("studio_note_ssg", ssg, 12)
    lines.append("")
    lines.append("static inline const char *studio_note_name(int n) {")
    lines.append("  static const char *const nm[12] = {")
    lines.append('    "C","C#","D","D#","E","F","F#","G","G#","A","A#","B" };')
    lines.append("  static char b[5];")
    lines.append("  if (n < 0 || n > 127) return \"--\";")
    lines.append("  const char *s = nm[n % 12];")
    lines.append("  int i = 0;")
    lines.append("  while (*s) b[i++] = *s++;")
    lines.append("  b[i++] = (char)('0' + n / 12 - 1);")
    lines.append("  b[i] = 0;")
    lines.append("  return b;")
    lines.append("}")
    lines.append("#endif /* STUDIO_NOTES_H */")
    with open("firmware/studio/notes.h", "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote firmware/studio/notes.h")
    for n in (45, 57, 60, 69, 81):
        print(f"  note {n}: blk={blk[n]} fnum={fnum[n]} ssg={ssg[n]} ({midi_hz(n):.1f} Hz)")


if __name__ == "__main__":
    main()
